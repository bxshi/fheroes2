#pragma once

#include <string>
#include <string_view>

namespace Encoding
{
    // Converts Big5 encoded text to UTF-8. ASCII bytes are copied as is. A valid and defined two-byte
    // Big5 sequence is converted to its UTF-8 representation. Every invalid byte or undefined byte pair
    // is replaced by '?': one byte is consumed for an invalid lead byte (or a lead byte not followed by
    // a valid trail byte), two bytes are consumed for an undefined pair with a valid trail byte.
    std::string big5ToUtf8( const std::string_view text );
}
