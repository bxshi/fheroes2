#pragma once

#include <array>
#include <cstddef>
#include <cstdint>

namespace Encoding::detail
{
    // GB2312 (EUC-CN) lead and trail bytes are in the ranges [0xA1; 0xF7] and [0xA1; 0xFE].
    constexpr uint8_t gb2312LeadFirst{ 0xA1 };
    constexpr uint8_t gb2312LeadLast{ 0xF7 };
    constexpr uint8_t gb2312TrailFirst{ 0xA1 };
    constexpr uint8_t gb2312TrailLast{ 0xFE };

    constexpr size_t gb2312TrailCount{ gb2312TrailLast - gb2312TrailFirst + 1 };
    constexpr size_t gb2312LeadCount{ gb2312LeadLast - gb2312LeadFirst + 1 };
    constexpr size_t gb2312TableSize{ gb2312LeadCount * gb2312TrailCount };

    static_assert( gb2312TrailCount == 94 );

    // Maps a GB2312 byte pair to a Unicode BMP code point (0 means that the pair is undefined).
    // Index: ( lead - gb2312LeadFirst ) * gb2312TrailCount + ( trail - gb2312TrailFirst ).
    // The table is generated by script/tools/generate_gb2312_table.py and is defined in gb2312_table.cpp.
    extern const std::array<uint16_t, gb2312TableSize> gb2312Table;
}
