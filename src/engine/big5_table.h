#pragma once

#include <array>
#include <cstddef>
#include <cstdint>

namespace Encoding::detail
{
    // Big5 lead bytes are in the range [0x81; 0xFE].
    constexpr uint8_t big5LeadFirst{ 0x81 };
    constexpr uint8_t big5LeadLast{ 0xFE };

    // Big5 trail bytes are in the ranges [0x40; 0x7E] and [0xA1; 0xFE].
    constexpr uint8_t big5TrailLowFirst{ 0x40 };
    constexpr uint8_t big5TrailLowLast{ 0x7E };
    constexpr uint8_t big5TrailHighFirst{ 0xA1 };
    constexpr uint8_t big5TrailHighLast{ 0xFE };

    constexpr size_t big5TrailLowCount{ big5TrailLowLast - big5TrailLowFirst + 1 };
    constexpr size_t big5TrailCount{ big5TrailLowCount + ( big5TrailHighLast - big5TrailHighFirst + 1 ) };
    constexpr size_t big5LeadCount{ big5LeadLast - big5LeadFirst + 1 };
    constexpr size_t big5TableSize{ big5LeadCount * big5TrailCount };

    static_assert( big5TrailCount == 157 );

    // Maps a Big5 byte pair to a Unicode BMP code point (0 means that the pair is undefined).
    // Index: ( lead - big5LeadFirst ) * big5TrailCount + trailIndex, where trailIndex is
    // ( trail - 0x40 ) for trail bytes [0x40; 0x7E] and ( trail - 0xA1 + 63 ) for trail bytes [0xA1; 0xFE].
    // The table is generated by script/tools/generate_big5_table.py and is defined in big5_table.cpp.
    extern const std::array<uint16_t, big5TableSize> big5Table;
}
