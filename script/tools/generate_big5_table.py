"""
Generates src/engine/big5_table.cpp: a Big5 to Unicode (BMP) lookup table.

The table is built using Python's plain 'big5' codec (not CP950). It covers lead
bytes 0x81 - 0xFE and trail bytes 0x40 - 0x7E and 0xA1 - 0xFE (157 trail values per
lead byte). Each entry is the BMP code point of the character or 0 if the byte
pair is undefined.

Usage (from the project root directory):
    python3 script/tools/generate_big5_table.py [--year YEAR] [output_file]
"""

import argparse
import os
import sys

LEAD_FIRST = 0x81
LEAD_LAST = 0xFE
TRAIL_RANGES = ((0x40, 0x7E), (0xA1, 0xFE))
VALUES_PER_LINE = 16
DEFAULT_COPYRIGHT_YEAR = 2026

SCRIPT_PATH = "script/tools/generate_big5_table.py"
DEFAULT_OUTPUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..",
    "..",
    "src",
    "engine",
    "big5_table.cpp",
)

COPYRIGHT_HEADER = """/***************************************************************************
 *   fheroes2: https://github.com/ihhub/fheroes2                           *
 *   Copyright (C) {YR}                                                    *
 *                                                                         *
 *   This program is free software; you can redistribute it and/or modify  *
 *   it under the terms of the GNU General Public License as published by  *
 *   the Free Software Foundation; either version 2 of the License, or     *
 *   (at your option) any later version.                                   *
 *                                                                         *
 *   This program is distributed in the hope that it will be useful,       *
 *   but WITHOUT ANY WARRANTY; without even the implied warranty of        *
 *   MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the         *
 *   GNU General Public License for more details.                          *
 *                                                                         *
 *   You should have received a copy of the GNU General Public License     *
 *   along with this program; if not, write to the                         *
 *   Free Software Foundation, Inc.,                                       *
 *   59 Temple Place - Suite 330, Boston, MA  02111-1307, USA.             *
 ***************************************************************************/"""


def trail_bytes():  # pylint: disable=missing-function-docstring
    result = []
    for first, last in TRAIL_RANGES:
        result.extend(range(first, last + 1))
    return result


def build_table():
    """Returns a list of BMP code points (0 for undefined pairs) in lead-major order."""
    trails = trail_bytes()
    table = []

    for lead in range(LEAD_FIRST, LEAD_LAST + 1):
        for trail in trails:
            try:
                decoded = bytes([lead, trail]).decode("big5")
            except UnicodeDecodeError:
                table.append(0)
                continue

            if len(decoded) != 1 or ord(decoded) > 0xFFFF:
                raise ValueError(
                    f"Unexpected decoding result for 0x{lead:02X} 0x{trail:02X}: {decoded!r}"
                )

            table.append(ord(decoded))

    return table


def generate_source(table, year):  # pylint: disable=missing-function-docstring
    lines = [
        COPYRIGHT_HEADER.replace("{YR}", f"{year}"),
        "",
        f"// This file is generated by {SCRIPT_PATH}. Do not edit it manually.",
        "// Source: Python 'big5' codec. Index: ( lead - 0x81 ) * 157 + trailIndex, where",
        "// trailIndex is ( trail - 0x40 ) for trail bytes 0x40 - 0x7E and ( trail - 0xA1 + 63 )",
        "// for trail bytes 0xA1 - 0xFE. A value of 0 means that the byte pair is undefined.",
        "",
        '#include "big5_table.h"',
        "",
        "namespace Encoding::detail",
        "{",
        "    // clang-format off",
        "    const std::array<uint16_t, big5TableSize> big5Table{ {",
    ]

    for offset in range(0, len(table), VALUES_PER_LINE):
        chunk = table[offset : offset + VALUES_PER_LINE]
        lines.append("        " + ", ".join(f"0x{value:04X}" for value in chunk) + ",")

    # Remove the trailing comma after the last value.
    lines[-1] = lines[-1][:-1]

    lines.extend(["    } };", "    // clang-format on", "}", ""])

    return "\n".join(lines)


def main():  # pylint: disable=missing-function-docstring
    parser = argparse.ArgumentParser(
        description="Generate the Big5 to Unicode lookup table."
    )
    parser.add_argument(
        "--year",
        type=int,
        default=DEFAULT_COPYRIGHT_YEAR,
        help=f"copyright year to put into the generated file (default: {DEFAULT_COPYRIGHT_YEAR})",
    )
    parser.add_argument(
        "output_file",
        nargs="?",
        default=DEFAULT_OUTPUT,
        help="output file (default: src/engine/big5_table.cpp)",
    )
    args = parser.parse_args()

    table = build_table()
    source = generate_source(table, args.year)

    with open(args.output_file, "w", encoding="utf-8", newline="\n") as output_file:
        output_file.write(source)

    defined = sum(1 for value in table if value != 0)
    print(
        f"Written {len(table)} entries ({defined} defined) to {os.path.normpath(args.output_file)}",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
